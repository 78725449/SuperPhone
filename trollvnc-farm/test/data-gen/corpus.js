export function validateCorpus() {
  const errs = [];
  const need = { FAMILY_NAMES: 100, GIVEN_NAMES: 400, NICKNAMES: 40,
    'ROLE_WORDS.family': 100, 'ROLE_WORDS.service': 80, 'ROLE_WORDS.business': 30, 'ROLE_WORDS.work': 30,
    'SMS_TEMPLATES.code': 80, 'SMS_TEMPLATES.express': 70, 'SMS_TEMPLATES.bank': 70,
    'SMS_TEMPLATES.carrierSms': 70, 'SMS_TEMPLATES.family': 140 };
  const pools = { FAMILY_NAMES, GIVEN_NAMES, NICKNAMES, 'ROLE_WORDS.family': ROLE_WORDS.family,
    'ROLE_WORDS.service': ROLE_WORDS.service, 'ROLE_WORDS.business': ROLE_WORDS.business, 'ROLE_WORDS.work': ROLE_WORDS.work };
  for (const [k, min] of Object.entries(need)) {
    const arr = k.startsWith('SMS_TEMPLATES') ? SMS_TEMPLATES[k.split('.')[1]] : pools[k];
    if (!arr || arr.length < min) errs.push(`${k} 数量不足 ${(arr && arr.length) || 0}/${min}`);
    if (arr && new Set(arr).size !== arr.length) errs.push(`${k} 存在重复项`);
  }
  for (const [k, arr] of Object.entries({ code: SMS_TEMPLATES.code, express: SMS_TEMPLATES.express, bank: SMS_TEMPLATES.bank, carrierSms: SMS_TEMPLATES.carrierSms, family: SMS_TEMPLATES.family })) {
    for (const t of arr) {
      const vars = [...t.matchAll(/\{([a-z0-9]+)\}/g)].map((m) => m[1]);
      for (const v of vars) {
        if (!KNOWN_VARS.includes(v)) errs.push(`模板未知变量{${v}}[${k}]: ${t}`);
      }
      if (t.length > 70) errs.push(`模板过长(>70)[${k}]: ${t}`);
    }
  }
  // marketing 行业对象检查
  let mktTotal = 0;
  for (const [g, v] of Object.entries(SMS_TEMPLATES.marketing)) {
    if (!Array.isArray(v.templates) || !Array.isArray(v.brands)) { errs.push(`marketing.${g} 结构异常`); continue; }
    if (v.brands.length < 3) errs.push(`marketing.${g} 品牌池不足(<${3}): ${v.brands.length}`);
    mktTotal += v.templates.length;
    for (const t of v.templates) {
      const vars = [...t.matchAll(/\{([a-z0-9]+)\}/g)].map((m) => m[1]);
      for (const vv of vars) if (!KNOWN_VARS.includes(vv)) errs.push(`营销模板未知变量{${vv}}[${g}]: ${t}`);
      if (t.length > 70) errs.push(`营销模板过长[${g}]: ${t}`);
      if (!t.includes('【')) errs.push(`营销模板缺标签[${g}]: ${t}`);
    }
  }
  if (mktTotal < 150) errs.push(`SMS_TEMPLATES.marketing 总模板不足 ${mktTotal}/150`);
  // 词池互斥
  for (const w of ROLE_WORDS.service) {
    if (KINSHIP_SUBSTRINGS.some((c) => w.includes(c))) errs.push(`service 词含称谓字: ${w}`);
  }
  for (const w of ROLE_WORDS.family) {
    if (ROLE_WORDS.service.some((x) => w.includes(x)) || ROLE_WORDS.business.some((x) => w.includes(x)) || ROLE_WORDS.work.some((x) => w.includes(x))) {
      errs.push(`family 词与其它池重叠: ${w}`);
    }
  }
  for (const w of ROLE_WORDS.business) {
    if (ROLE_WORDS.service.some((x) => w.includes(x))) errs.push(`business 词含 service 子串: ${w}`);
  }
  for (const w of ROLE_WORDS.work) {
    if (ROLE_WORDS.service.some((x) => w.includes(x))) errs.push(`work 词含 service 子串: ${w}`);
    if (ROLE_WORDS.business.some((x) => w.includes(x))) errs.push(`work 词含 business 子串: ${w}`);
  }
  const brandNeed = { banks: 20, couriers: 15, platforms: 20, stations: 20, estates: 20, orgs: 20, products: 30, ecoms: 15, brands: 30 };
  for (const [k, min] of Object.entries(brandNeed)) {
    if (!BRAND_POOLS[k] || BRAND_POOLS[k].length < min) errs.push(`BRAND_POOLS.${k} 数量不足 ${(BRAND_POOLS[k] && BRAND_POOLS[k].length) || 0}/${min}`);
    if (BRAND_POOLS[k] && new Set(BRAND_POOLS[k]).size !== BRAND_POOLS[k].length) errs.push(`BRAND_POOLS.${k} 存在重复项`);
  }
  return errs; // 空数组 = 通过
}
